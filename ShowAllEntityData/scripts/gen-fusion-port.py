#!/usr/bin/env python3
"""Generate (or print) the rec-dup finding's verbatim port of Fusion's matching code.

Fusion (majkinetor, userscripts/fusion/fusion.user.js in the clone debug/majkinetor/) decides
which recordings are duplicates. The "Possible duplicate recording" finding ports its gates
VERBATIM, so SAED and Fusion agree on what a duplicate is and the finding works without Fusion
installed (org/majkinetor.org, "Possible duplicate recordings"). This script cuts each
declaration named in scripts/fusion-port-map.json out of the clone, renames the identifiers
of its "rename" table (never a property: `sig.isrcConflict`, `{ placeConflict: null }` stay),
indents it into the IIFE and puts a JSDoc block above it. Nothing else of the body changes;
scripts/check-fusion-port.js undoes the renames and compares the result with the clone.

The clone is untrusted third-party code: this script only READS it as text.

usage: python3 scripts/gen-fusion-port.py            # print the section
       python3 scripts/gen-fusion-port.py --write    # replace the section between its markers
                                                     # in ShowAllEntityData.user.js
"""
import json
import re
import sys

MAP = 'scripts/fusion-port-map.json'
CLONE = 'debug/majkinetor/'
USERSCRIPT = 'ShowAllEntityData.user.js'
BEGIN = '    // ── Fusion port BEGIN (generated by scripts/gen-fusion-port.py; do not edit by hand) ──'
END = '    // ── Fusion port END ──'


def load_map():
    """The port map (rename table, declarations, settings)."""
    with open(MAP, encoding='utf-8') as f:
        return json.load(f)


def decl_lines(lines, name):
    """The clone lines of one top-level declaration `function name(` / `const name =`.

    A declaration ends at the first line ending in ';' or '}' whose next non-blank line starts
    in column 0 (Fusion's top level), so a one-line declaration is one line.
    """
    start_re = re.compile(r'^(?:async\s+)?(?:function\s+' + re.escape(name) + r'\s*\(|const\s+' + re.escape(name) + r'\s*=)')
    starts = [i for i, ln in enumerate(lines) if start_re.match(ln)]
    if len(starts) != 1:
        raise SystemExit(f'{name}: {len(starts)} declarations in the clone')
    i = starts[0]
    nxt = i + 1
    while nxt < len(lines) and not lines[nxt].strip():
        nxt += 1
    if lines[i].rstrip().endswith((';', '}')) and (nxt >= len(lines) or not lines[nxt][:1].isspace()):
        return lines[i:i + 1]
    for j in range(i + 1, len(lines)):
        if lines[j].strip() and not lines[j][:1].isspace():
            if lines[j][:1] in '}])':
                return lines[i:j + 1]
            k = j
            while not lines[k - 1].strip():
                k -= 1
            return lines[i:k]
    raise SystemExit(f'{name}: no end found')


def rename_re(rename):
    """One regex for every identifier to rename that is not a property (never after '.')."""
    names = sorted(rename, key=len, reverse=True)
    return re.compile(r'(?<![\w$.])(' + '|'.join(map(re.escape, names)) + r')(?![\w$])')


def rename_line(rx, rename, ln):
    """Rename the identifiers of one line, except an object key (`{ name:` / `, name:`)."""
    def sub(mm):
        before = ln[:mm.start()].rstrip()
        after = ln[mm.end():].lstrip()
        if after.startswith(':') and not after.startswith('::') and (not before or before[-1] in '{,'):
            return mm.group(1)
        return rename[mm.group(1)]
    return rx.sub(sub, ln)


def ported(m, lines):
    """The ported section's lines (indented, JSDoc'd), without its markers."""
    rx = rename_re(m['rename'])
    out = [
        '    // ── Possible duplicate recordings (rec-dup): Fusion\'s matching ──',
        '    // Ported from majkinetor\'s Fusion (' + m['source'] + '),',
        '    // verbatim: only renamed (normName -> _fzNormName, ...; the table is',
        '    // scripts/fusion-port-map.json) and indented. Permission #938',
        '    // (2026-11-17). Fusion reads its SETTINGS; here they are its defaults, fixed.',
        '    // scripts/check-fusion-port.js compares every body with the clone.',
        '',
        '    /** Fusion\'s SETTINGS_DEFAULTS this port reads (length tolerance, gross length), in ms. */',
        '    const _FZ_SETTINGS = Object.freeze({ ' + ', '.join(f'{k}: {v}' for k, v in m['settings'].items()) + ' });',
    ]
    for d in m['decls']:
        body = decl_lines(lines, d['name'])
        out.append('')
        out.append('    /**')
        for dl in d['doc'].split('\n'):
            out.append(('     * ' + dl).rstrip())
        out.append('     */')
        for ln in body:
            ln = rename_line(rx, m['rename'], ln.rstrip())
            out.append(('    ' + ln).rstrip() if ln else '')
    return out


def main():
    """Print the section, or write it into the userscript between its markers."""
    m = load_map()
    with open(CLONE + m['source'], encoding='utf-8') as f:
        lines = f.read().split('\n')
    sec = ported(m, lines)
    if '--write' not in sys.argv:
        print('\n'.join(sec))
        return 0
    with open(USERSCRIPT, encoding='utf-8') as f:
        text = f.read()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SystemExit('markers not found exactly once; place them first')
    a = text.index(BEGIN) + len(BEGIN)
    b = text.index(END)
    new = text[:a] + '\n' + '\n'.join(sec).replace('\t', '    ') + '\n' + text[b:]
    with open(USERSCRIPT, 'w', encoding='utf-8') as f:
        f.write(new)
    print(f'wrote {len(sec)} lines between the markers')
    return 0


if __name__ == '__main__':
    sys.exit(main())
