#!/usr/bin/env python3
"""Writes two fixtures whose <body> has the shape of the LIVE pages, from the saved ones.

The saved fixtures `tests/fixtures/dg-search.html` and `tests/fixtures/ia-details.html`
put the site's header and content straight into <body>. The live pages do not
(vzell's snapshots, 2026-11-25: debug/d-search-ctrlmp-bug.html,
debug/ia-release-ctrlmp-bug.html), and the original-page switch's first rules,
which named those elements, hid nothing there. This wraps the saved content the
way the live <body> does:

- Discogs' search (Next.js): `<div hidden>`, then `<div class="flex flex-1 flex-col">`
  around everything the saved page had, then an iframe, `<next-route-announcer>`
  and the cookie banner root `#onetrust-consent-sdk`.
- An archive.org item: a skip link, `<div id="wrap">` around the saved content,
  then an `<img>`, `<modal-manager>`, `#cboxOverlay`, `#colorbox`, `#fc-root`.

Usage: python3 scripts/make-live-shape-fixtures.py  (writes
tests/fixtures/dg-search-next.html and tests/fixtures/ia-details-wrap.html)
"""
import pathlib
import re
import sys

FIX = pathlib.Path(__file__).resolve().parent.parent / 'tests' / 'fixtures'


def rewrap(src_name, dst_name, before, wrap_open, wrap_close, after):
    """Wraps the body content of one saved fixture and writes the result.

    Args:
        src_name: the saved fixture's file name.
        dst_name: the new fixture's file name.
        before: markup put first in <body>, before the wrapper.
        wrap_open: the wrapper's start tag.
        wrap_close: the wrapper's end tag.
        after: markup put after the wrapper, at the end of <body>.
    """
    src = (FIX / src_name).read_text(encoding='utf-8')
    m = re.search(r'(<body[^>]*>)(.*)(</body>)', src, re.S)
    if not m:
        sys.exit(f'{src_name}: no <body>')
    body = before + wrap_open + m.group(2) + wrap_close + after
    out = src[:m.start()] + m.group(1) + body + m.group(3) + src[m.end():]
    note = (f'<!-- Generated by scripts/make-live-shape-fixtures.py from {src_name}: '
            'the live page\'s <body> shape (2026-11-25). Do not edit by hand. -->\n')
    (FIX / dst_name).write_text(note + out, encoding='utf-8')
    print(f'{dst_name}: {len(out)} bytes')


rewrap('dg-search.html', 'dg-search-next.html',
       '<div hidden=""><!--$--><!--/$--></div>',
       '<div class="flex flex-1 flex-col">', '</div>',
       '<iframe title="fixture" style="display:none"></iframe>'
       '<next-route-announcer></next-route-announcer>'
       '<div id="onetrust-consent-sdk"></div>')
rewrap('ia-details.html', 'ia-details-wrap.html',
       '<a href="#maincontent" class="hidden-for-screen-readers">Skip to main content</a>',
       '<div id="wrap" itemscope="" itemtype="http://schema.org/AudioObject">', '</div>',
       '<img alt="" src="data:,">'
       '<modal-manager></modal-manager>'
       '<div id="cboxOverlay" style="display:none"></div>'
       '<div id="colorbox" style="display:none"></div>'
       '<div id="fc-root"></div>')
